/**
 * Generates src/config/defaultConfig.js directly from _migration/extracted-config.json
 * so the migrated default mappings are guaranteed to be byte-for-byte equivalent.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');

const source = JSON.parse(readFileSync(resolve(here, 'extracted-config.json'), 'utf8'));

const banner = [
  '// Default mapping configuration migrated verbatim from the original standalone',
  '// index.html (embedded-config block). Verified by _migration/verify-config.mjs.',
  '// Generated by _migration/generate-default-config.mjs - do not hand-edit.',
  '',
].join('\n');

const body = `export const defaultConfig = ${JSON.stringify(source, null, 2)};\n`;

writeFileSync(resolve(root, 'src/config/defaultConfig.js'), banner + body, 'utf8');
console.log('Wrote src/config/defaultConfig.js');
console.log('  columnMappings:', source.columnMappings.length);
