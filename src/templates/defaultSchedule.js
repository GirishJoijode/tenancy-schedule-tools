export const DEFAULT_SCHEDULE_COLUMNS = attachFieldLogic(DEFAULT_SCHEDULE_COLUMN_DEFS, DEFAULT_FIELD_LOGIC);

export function isRenderedScheduleColumn(column) {
  return !column || column.rendered !== false;
}

export function getRenderedScheduleColumns(headingById) {
  var labels = headingById || {};
  return DEFAULT_SCHEDULE_COLUMNS.filter(isRenderedScheduleColumn).map(function (column) {
    return {
      id: column.id,
      label: labels[column.id] || column.label,
    };
  });
}
